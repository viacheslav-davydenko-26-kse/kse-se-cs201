# [Домен] Статистика / математичне моделювання — метод Монте-Карло
#
# [Опис завдання] Потрібно оцінити число π, не обчислюючи його напряму, а
# моделюючи випадкові точки. Уявіть квадрат зі стороною 2 (координати від
# -1 до 1 по обох осях) і вписане в нього коло радіусом 1. Частка
# випадкових точок квадрата, що потрапляють у коло, наближено пов'язана
# з відношенням площ кола і квадрата, а звідси можна вивести оцінку π.
#
# Що потрібно дослідити: функцію random.uniform(a, b), яка генерує
# випадкове дробове число в заданому діапазоні.
#
# Завдання: створіть num_points (наприклад, 10000) і лічильник
# points_inside_circle зі значенням 0. За допомогою циклу for виконайте
# num_points ітерацій: на кожній згенеруйте випадкові x і y у діапазоні
# від -1 до 1 функцією random.uniform(-1, 1), обчисліть відстань точки
# від центру ((x**2 + y**2) ** 0.5), і якщо вона не перевищує 1 —
# збільшіть points_inside_circle на 1. Після циклу обчисліть
# pi_estimate = 4 * points_inside_circle / num_points і виведіть його.
#
# Пояснення: чим більше num_points, тим точніша оцінка — спробуйте
# порівняти результат для 100, 10000 і 1 000 000 точок і подивіться, як
# змінюється похибка відносно реального значення π (3.14159...).
num_points = 1_000_000
points_inside_circle = 0

for i in range(num_points):
    x = random.uniform(-1, 1)
    y = random.uniform(-1, 1)
    r = ((x**2 + y**2) ** 0.5)

    if r <= 1:
        points_inside_circle += 1

pi_estimate = 4 * points_inside_circle / num_points
print(pi_estimate)

