# [Домен] Особисті фінанси — модель накопичення на депозиті
#
# [Опис завдання] Ви відкриваєте банківський депозит із певною річною
# процентною ставкою, яка нараховується щомісяця, і додатково
# поповнюєте його щомісяця фіксованою сумою. Потрібно змоделювати, як
# зростає баланс з місяця в місяць, і визначити, коли буде досягнута
# цільова сума.
#
# Що потрібно дослідити: як перевести річну процентну ставку в
# щомісячну (поділити на 12).
#
# Завдання: створіть balance (наприклад, 0), monthly_deposit (наприклад,
# 3000), annual_rate (наприклад, 0.08, тобто 8%) і goal (наприклад,
# 100000). Обчисліть monthly_rate = annual_rate / 12. Створіть
# лічильник month зі значенням 0 і список balance_history. За допомогою
# циклу while balance < goal: спочатку нарахуйте відсотки на поточний
# баланс (balance += balance * monthly_rate), потім додайте
# monthly_deposit, збільшіть month на 1 і додайте round(balance, 2) у
# balance_history. Після циклу виведіть, за скільки місяців і років
# (місяці // 12 та місяці % 12) досягнуто цільової суми, а також
# фінальний баланс.
#
# Пояснення: порядок дій важливий — спочатку нараховуються відсотки на
# те, що вже лежить на депозиті, і лише потім додається нове щомісячне
# поповнення, на яке відсотки цього самого місяця ще не нараховуються.
balance = 0
monthly_deposit = 3000
annual_rate = 0.08
goal = 100_000
monthly_rate = annual_rate / 12
month = 0
balance_history = []

while balance < goal:
    balance += balance * monthly_rate
    balance += monthly_deposit
    month += 1
    balance_history.append(round(balance, 2))

print(month // 12, month % 12, balance_history[-1])
