# [Домен] Маркетинг — модель вірусного поширення промокоду
#
# [Опис завдання] Компанія випустила промокод, і люди діляться ним у
# соцмережах. Щодня кожна людина, яка вже знає промокод, розповідає про
# нього кільком новим людям. Потрібно змоделювати, скільки людей
# знатиме про промокод з кожним днем, поки не буде охоплено всю
# аудиторію.
#
# Що потрібно дослідити: вбудовану функцію min() — вона знадобиться, щоб
# кількість поінформованих людей математично не перевищила розмір
# аудиторії.
#
# Завдання: створіть total_audience (наприклад, 5000), informed зі
# значенням 1 (перша людина, яка знає промокод) і contacts_per_person
# (скільки нових людей у середньому інформує один обізнаний за день,
# наприклад 3). Створіть лічильник day зі значенням 0 і список
# informed_history. За допомогою циклу while informed < total_audience:
# обчисліть, скільки людей дізналося сьогодні, як
# min(informed * contacts_per_person, total_audience - informed) —
# щоб не "переповнити" аудиторію, додайте це число до informed,
# збільшіть day на 1 і додайте поточне значення informed в
# informed_history. Після циклу виведіть, за скільки днів (day) уся
# аудиторія дізналась про промокод, і виведіть informed_history, щоб
# побачити криву зростання.
#
# Пояснення: без обмеження через min() кількість "поінформованих" могла
# б математично вийти більшою за total_audience, чого в реальності
# статися не може — тому саме ця межа є важливою частиною моделі.
total_audience = 5000
informed = 1
contacts_per_person = 3
day = 0
informed_history = []

while informed < total_audience:
    new_people = min(informed * contacts_per_person, total_audience - informed)
    informed += new_people
    day += 1
    informed_history.append(informed)

print(day, informed_history)


