print("# %% ========== Завдання 1 ==========")
# [Домен] Фізика / математичне моделювання — випадкове блукання (random walk)
#
# [Опис завдання] Уявний мандрівник починає рух з позиції 0. На кожному
# кроці він випадково рухається або на +1, або на -1. Потрібно
# змоделювати задану кількість кроків і проаналізувати підсумковий рух.
#
# Що потрібно дослідити: модуль random, зокрема random.choice() —
# функцію, яка випадково обирає один елемент зі списку варіантів.
#
# Завдання: створіть змінну position зі значенням 0 і кількість кроків
# num_steps (наприклад, 100). Створіть порожній список history. За
# допомогою циклу for виконайте num_steps ітерацій: на кожній випадково
# оберіть крок +1 або -1 через random.choice([1, -1]), додайте його до
# position і збережіть нову позицію в history методом append(). Після
# циклу виведіть фінальну позицію position, а також максимальну
# відстань від нуля, яку мандрівник коли-небудь досягав за весь рух.
#
# Пояснення: щоб знайти максимальну відстань від нуля, порівнюйте не самі
# значення позицій зі history, а їхні модулі (abs(value)) — віддалення в
# мінус так само далеко, як і в плюс.
import random

position = 0
num_steps = 100
history = []

max_distance = 0
for i in range(num_steps):
    step = random.choice([1, -1])
    position += step
    history.append(position)

    if abs(position) > max_distance:
        max_distance = abs(position)

print(position)
print(max_distance)
# or
print(max([abs(h) for h in history]))

