# [Домен] Біологія / екологічне моделювання — ріст популяції
#
# [Опис завдання] На острові живе популяція кроликів. Щороку вона
# зростає за фіксованою ставкою приросту, але острів має обмежену
# місткість — максимальну кількість кроликів, яку він може прогодувати,
# тому зростання поступово сповільнюється, наближаючись до цієї межі.
# Потрібно змоделювати чисельність популяції за кілька років.
#
# Що потрібно дослідити: формулу логістичного росту —
# population = population + growth_rate * population * (1 - population / capacity)
# — стандартну модель обмеженого росту з екології.
#
# Завдання: створіть population (наприклад, 10), growth_rate (наприклад,
# 0.3), capacity (наприклад, 500) і years (наприклад, 30). Створіть
# список population_history і одразу додайте туди початкове значення
# population. За допомогою циклу for на кожен рік обчислюйте нове
# значення population за формулою вище і додавайте його в
# population_history. Після циклу виведіть population_history цілком, а
# також визначте (порівнюючи значення зі списку з 0.9 * capacity через
# if), на який за номером рік популяція вперше перевищила 90% від
# місткості острова.
#
# Пояснення: формула сама собою вже "гальмує" зростання, коли population
# наближається до capacity, — множник (1 - population / capacity) стає
# дедалі меншим, тому приріст сповільнюється природним чином, без
# додаткових умов у формулі.
population = 10
growth_rate = 0.3
capacity = 500
years = 30

population_history = [population]

for year in range(years):
    population = population + growth_rate * population * (1 - population / capacity)
    population_history.append(population)

print(population_history)

for year, p in enumerate(population_history):
    if p > 0.9 * capacity:
        print(year + 1)
        break


