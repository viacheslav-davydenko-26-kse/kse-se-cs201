# ---------- Приклад 2 — функції + словники, параметри за замовчуванням, **kwargs ----------
def build_summary(scores, passing=60, **extra):
    summary = {name: ("pass" if score >= passing else "fail")
               for name, score in scores.items()}
    summary.update(extra)
    return summary


