# %% ========== БЛОК 2. РОЗБІР БАЗОВИХ ЗАВДАНЬ (15 хв) ==========

# ---------- Приклад 1 — одна помилка, один except ----------
try:
    number = int(input("Введіть ціле число: "))
    print(f"Квадрат числа: {number ** 2}")
except ValueError:
    print("Це не схоже на ціле число!")

# Питання:
# 1. Що станеться, якщо ввести "7"?
# 2. Що станеться, якщо ввести "abc"? Чи виконається print(f"Квадрат...")?


# ---------- Приклад 2 — кілька except для різних типів помилок ----------
try:
    a = int(input("Введіть чисельник: "))
    b = int(input("Введіть знаменник: "))
    print(f"Результат: {a / b}")
except ValueError:
    print("Потрібно вводити лише цілі числа!")
except ZeroDivisionError:
    print("На нуль ділити не можна!")

# Питання:
# 1. Як Python обирає, який саме except виконати?
# 2. Що виведе програма для пари "10"/"2", "abc"/"2", "10"/"0"?


# ---------- Приклад 3 — повна конструкція try-except-else-finally ----------
try:
    price = float(input("Введіть ціну товару: "))
except ValueError:
    print("Некоректна ціна!")
else:
    print(f"Ціна прийнята: {price}")
finally:
    print("Перевірку завершено")

# Питання:
# 1. У якому порядку виконаються блоки, якщо ввести коректне число?
# 2. У якому порядку виконаються блоки, якщо ввести некоректне значення?
#    Чи виконається else в цьому випадку?


