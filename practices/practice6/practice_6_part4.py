# ---------- Завдання 4.1 (просте) ----------
# Напишіть програму, яка через input() запитує ціле число.
# Якщо введення коректне — виведіть "Ви ввели: <число>".
# Якщо некоректне — виведіть повідомлення про помилку (try-except).
try:
    number = int(input("Введіть ціле число: "))
except ValueError:
    print("Це має бути число!")
else:
    print("Ви ввели:", number)

# ---------- Завдання 4.2 (середнє) ----------
# Напишіть програму, яка запитує через input() два цілих числа і ділить
# перше на друге. Обробіть окремо випадок некоректного вводу і окремо
# випадок ділення на нуль — з різними повідомленнями для кожного.
try:
    a = int(input("Введіть ціле число, яке будемо ділити: "))
    b = int(input("Введіть ціле число, яке буде дільником: "))
    result = a / b
except ValueError:
    print("Це має бути число!")
except ZeroDivisionError:
    print("Не можна ділити на нуль!")
else:
    print("Результат:", result)


# ---------- Завдання 4.3 (складніше) ----------
# Дано список fruits = ["яблуко", "банан", "вишня"]. Напишіть програму,
# яка запитує через input() індекс елемента списку. Використайте повну
# конструкцію try-except-else-finally:
#   - некоректний індекс (не число) -> ValueError;
#   - індекс поза межами списку -> IndexError;
#   - успіх -> у блоці else вивести знайдений фрукт;
#   - у блоці finally в будь-якому випадку вивести "Перевірку завершено".
fruits = ["яблуко", "банан", "вишня"]

try:
    index = int(input("Введіть індекс: "))
    fruit = fruits[index]
except ValueError:
    print("Це має бути число!")
except IndexError:
    print("Індекс поза межами списку.")
else:
    print("Ваш фрукт:", fruit)
finally:
    print("Перевірку завершено.")
