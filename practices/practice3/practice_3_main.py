# ---------- Приклад 1 — комбінація if/elif/else з логічними операторами ----------
score = 85
attendance = 92

if score >= 90 and attendance >= 90:
    result = "відмінно з відзнакою"
elif score >= 90 or attendance >= 90:
    result = "відмінно"
elif score >= 70:
    result = "добре"
else:
    result = "потрібно перескласти"

print(result)

