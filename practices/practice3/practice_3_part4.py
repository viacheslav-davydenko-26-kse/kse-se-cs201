print("# ---------- Завдання 4.1 (просте) ----------")
# Створіть числову змінну. За допомогою вкладених if/elif/else визначте
# й виведіть одразу дві характеристики цього числа: чи воно додатне,
# від'ємне чи дорівнює нулю, і окремо — чи воно парне, чи непарне.
number = 10

if number == 0:
    print("дорівнює нулю")
elif number > 0:
    print("додатне")
else:
    print("від'ємне")

if number % 2 == 0:
    print("парне")
else:
    print("непарне")

print("# ---------- Завдання 4.2 (середнє) ----------")
# За допомогою циклу for і range() обчисліть суму всіх чисел від 1 до 50,
# які одночасно кратні і 3, і 5 (скористайтеся оператором % та логічним
# and), і виведіть цю суму.
total = 0
for i in range(1, 51):
    if (i % 3 == 0) and (i % 5 == 0):
        total += i
print(total)

print("# ---------- Завдання 4.3 (складніше) ----------")
# Створіть змінну limit з довільним числовим значенням (наприклад, 50).
# За допомогою циклу while моделюйте накопичення суми непарних чисел:
# на кожному кроці беріть наступне непарне число (1, 3, 5, 7, ...) і
# ведіть лічильник кроків. Кожне третє за порядком непарне число НЕ
# додавайте до суми (скористайтесь continue, але лічильник кроків при
# цьому все одно повинен збільшуватись). Цикл має зупинитись (break),
# щойно сума total перевищить limit. Виведіть фінальне значення total і
# кількість кроків циклу.
limit = 50
total = 0
step_count = 0
index = 1

while total <= limit: 
    step_count += 1
    if step_count % 3 != 0:
        total += index
    index += 2 

print(total, step_count)
