"""
Є текстовий файл numbers.txt, де кожен рядок містить одне число.
Потрібно:
1. прочитати всі числа з файлу;
2. порахувати їх суму та середнє арифметичне;
3. записати результат у новий файл result.txt у форматі:
   Сума: <сума>
   Середнє: <середнє>

Підказки, якщо застрягли:
- Кожен рядок, прочитаний з файлу, — це рядок (str), тому перед
  додаванням його треба перетворити в число: int(line) або float(line).
- Не забувайте прибирати символ переносу рядка (line.strip())
  перед перетворенням у число.
- Для запису використовуйте режим 'w':
  with open("result.txt", "w", encoding="utf-8") as f:
"""

# TODO 1: відкрийте numbers.txt і прочитайте всі числа у список
FILE_PATH = "numbers.txt"
numbers = []
with open(FILE_PATH, "r") as f:
    for line in f:
        numbers.append(int(line.strip()))

# TODO 2: порахуйте суму та середнє арифметичне
total = sum(numbers) 
average = total / len(numbers) 

# TODO 3: запишіть результат у result.txt у форматі:
#   Сума: <сума>
#   Середнє: <середнє>

print(f"Сума: {total}")
print(f"Середнє: {average}")

with open("result.txt", "w", encoding="utf-8") as f:
    f.write(f"Сума: {total}\n")
    f.write(f"Середнє: {average}")
